//! 从 `NSPasteboard` 读一次快照。
//!
//! 只读需要的类型，读完即用；所有 AppKit 对象都在 autorelease pool 里创建。

use nsh_platform_macos::objc2::rc::{autoreleasepool, Retained};
use nsh_platform_macos::objc2::runtime::{AnyObject, ProtocolObject};
use nsh_platform_macos::objc2::AnyThread;
use nsh_platform_macos::objc2_app_kit::{
    NSBitmapImageFileType, NSBitmapImageRep, NSBitmapImageRepPropertyKey, NSPasteboard,
    NSPasteboardItem, NSPasteboardType, NSPasteboardTypeFileURL, NSPasteboardTypePNG,
    NSPasteboardTypeString, NSPasteboardTypeTIFF, NSPasteboardWriting, NSWorkspace,
};
use nsh_platform_macos::objc2_foundation::{NSArray, NSDictionary, NSString, NSURL};

use podnook_core::Snapshot;

/// 密码管理器约定：带这些类型的内容不记录。
const PRIVATE_TYPES: &[&str] = &[
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
];

const FILE_URL_TYPE: &str = "public.file-url";
const PNG_TYPE: &str = "public.png";
const TIFF_TYPE: &str = "public.tiff";

/// AppKit 的 pasteboard 类型常量是 extern static，读它需要 unsafe。
fn pb_type_string() -> &'static NSPasteboardType {
    unsafe { NSPasteboardTypeString }
}
fn pb_type_file_url() -> &'static NSPasteboardType {
    unsafe { NSPasteboardTypeFileURL }
}
fn pb_type_png() -> &'static NSPasteboardType {
    unsafe { NSPasteboardTypePNG }
}
fn pb_type_tiff() -> &'static NSPasteboardType {
    unsafe { NSPasteboardTypeTIFF }
}

/// 当前剪贴板的变化计数。
pub fn change_count() -> i64 {
    autoreleasepool(|_| NSPasteboard::generalPasteboard().changeCount() as i64)
}

/// 读一次剪贴板；没有可记录内容（或带隐私标记）时返回 `None`。
pub fn read_snapshot() -> Option<Snapshot> {
    autoreleasepool(|_| read_snapshot_inner())
}

fn read_snapshot_inner() -> Option<Snapshot> {
    let pasteboard = NSPasteboard::generalPasteboard();
    let types: Vec<String> = pasteboard
        .types()
        .map(|list| list.iter().map(|t| t.to_string()).collect())
        .unwrap_or_default();

    if types
        .iter()
        .any(|t| PRIVATE_TYPES.contains(&t.as_str()))
    {
        log::debug!("skip private pasteboard types: {types:?}");
        return None;
    }

    let (source_app, source_bundle) = frontmost_app();
    let mut snapshot = Snapshot {
        source_app,
        source_bundle,
        ..Default::default()
    };

    if types.iter().any(|t| t == FILE_URL_TYPE) {
        let paths = file_paths(&pasteboard);
        if !paths.is_empty() {
            snapshot.file_bytes = Some(
                paths
                    .iter()
                    .filter_map(|p| std::fs::metadata(p).ok())
                    .map(|m| m.len() as i64)
                    .sum(),
            );
            snapshot.file_uris = paths;
            return Some(snapshot);
        }
    }

    if types.iter().any(|t| t == PNG_TYPE || t == TIFF_TYPE) {
        if let Some((png, size)) = image_png(&pasteboard) {
            snapshot.image_png = Some(png);
            snapshot.image_size = Some(size);
            return Some(snapshot);
        }
    }

    if let Some(text) = pasteboard.stringForType(pb_type_string()) {
        let text = text.to_string();
        if !text.trim().is_empty() {
            snapshot.text = Some(text);
            return Some(snapshot);
        }
    }

    None
}

/// 复制瞬间的前台应用（名称与 bundle id）。
fn frontmost_app() -> (Option<String>, Option<String>) {
    let Some(app) = NSWorkspace::sharedWorkspace().frontmostApplication() else {
        return (None, None);
    };
    (
        app.localizedName().map(|s| s.to_string()),
        app.bundleIdentifier().map(|s| s.to_string()),
    )
}

/// 剪贴板里的文件路径（file URL → path）。
fn file_paths(pasteboard: &NSPasteboard) -> Vec<String> {
    let Some(items) = pasteboard.pasteboardItems() else {
        return Vec::new();
    };
    let mut paths = Vec::new();
    for item in items.iter() {
        let Some(value) = item.stringForType(pb_type_file_url()) else {
            continue;
        };
        let Some(url) = NSURL::URLWithString(&value) else {
            continue;
        };
        if let Some(path) = url.path() {
            paths.push(path.to_string());
        }
    }
    paths
}

/// 图片的 PNG 字节与像素尺寸；只有 TIFF 时先转 PNG。
fn image_png(pasteboard: &NSPasteboard) -> Option<(Vec<u8>, (u32, u32))> {
    if let Some(data) = pasteboard.dataForType(pb_type_png()) {
        let rep = NSBitmapImageRep::initWithData(NSBitmapImageRep::alloc(), &data)?;
        return Some((data.to_vec(), size_of(&rep)));
    }

    let data = pasteboard.dataForType(pb_type_tiff())?;
    let rep = NSBitmapImageRep::initWithData(NSBitmapImageRep::alloc(), &data)?;
    let size = size_of(&rep);
    let properties: Retained<NSDictionary<NSBitmapImageRepPropertyKey, AnyObject>> =
        NSDictionary::from_slices::<NSBitmapImageRepPropertyKey>(&[], &[]);
    let png = unsafe {
        rep.representationUsingType_properties(NSBitmapImageFileType::PNG, &properties)
    }?;
    Some((png.to_vec(), size))
}

fn size_of(rep: &NSBitmapImageRep) -> (u32, u32) {
    (
        rep.pixelsWide().max(0) as u32,
        rep.pixelsHigh().max(0) as u32,
    )
}

/// 把一个或多个文件写回系统剪贴板（`public.file-url` 条目）。
pub fn write_files(paths: &[String]) -> bool {
    if paths.is_empty() {
        return false;
    }
    autoreleasepool(|_| {
        let mut items: Vec<Retained<ProtocolObject<dyn NSPasteboardWriting>>> = Vec::new();
        for path in paths {
            let item = NSPasteboardItem::new();
            let ns_path = NSString::from_str(path);
            let url = NSURL::fileURLWithPath_isDirectory_relativeToURL(&ns_path, false, None);
            let Some(value) = url.absoluteString() else {
                continue;
            };
            if item.setString_forType(&value, pb_type_file_url()) {
                items.push(ProtocolObject::from_retained(item));
            }
        }
        if items.is_empty() {
            return false;
        }
        let array = NSArray::from_retained_slice(&items);
        let pasteboard = NSPasteboard::generalPasteboard();
        pasteboard.clearContents();
        pasteboard.writeObjects(&array)
    })
}

